// PIN, not a gate: checkStackSize is inlined into exactly the eight places it is
// called, so the push opcodes keep the unlimited-stack fast path (a compare and a
// return) without a call. The eight are Run, seven times, and the closure inside Run,
// once.
//
// Mutation that reddens it: inline reportStackOverflow's fmt.Sprintf body into
// checkStackSize. gc then prints `cannot inline (*MachineContext).checkStackSize`, no
// call site inlines, and the multiset is empty. Raising its cost past the budget of 80
// has the same effect. Adding a ninth call site, or moving one into a helper, fails the
// other way, which is intended: the multiset is a census, update it with the site.
//
// The test maps every `inlining call to (*MachineContext).checkStackSize` report in
// `go build -gcflags=-m=2` output to its enclosing function with go/parser, and asserts
// the multiset, not a count. A bare count of 8 survives the harm the pin exists to
// prevent: a site moved into a helper that cannot inline, a method value that gc
// reports against an `<autogenerated>:1` line, a longer name such as
// checkStackSizeFast matching by prefix. Reports against `<autogenerated>` are dropped
// and the callee name must match to the end of the line.
//
// This is strictly stronger than asserting `can inline`, which says only that the
// callee is under budget: it also catches a CALLER that stops inlining a still-inlinable
// callee, which is the harm the performance row describes. And `can inline` is not
// "within budget as the author meant" (the same run prints `can inline
// (*MachineContext).applyParameter.func1 with cost 130`).
//
// What it does not cover:
//
//   - The format. -m=2 output is not a stable interface. If the wording changes the
//     multiset is empty and the test fails loudly, which is acceptable; the fix is to
//     update the match, not to loosen the test.
//   - The build configuration. The subprocess builds the package plain, without -race,
//     -cover or -N -l, whatever the enclosing `go test` was given, so the result
//     describes the shipped optimizer. It still inherits GOARCH, GOAMD64, GOEXPERIMENT
//     and CGO_* from the environment, and inlining decisions can differ across them;
//     the census is calibrated on the default amd64/arm64 builds.
//   - Which statements. Seven of the eight are in Run; moving a call between two
//     statements of Run leaves the multiset unchanged.

package machine

import (
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"testing"

	qt "github.com/frankban/quicktest"
)

const checkStackSizeInlineMessage = "inlining call to (*MachineContext).checkStackSize"

// inlineReport matches one -m=2 line: `<file>:<line>:<col>: inlining call to <callee>`.
var inlineReport = regexp.MustCompile(`^(.+?):(\d+):\d+: ` + regexp.QuoteMeta(checkStackSizeInlineMessage) + `$`)

// enclosingFunc names the function a source line sits in: the declaration's name, with
// " (closure)" appended when the line is inside a function literal within it. It
// returns "" when the line is in no function.
func enclosingFunc(fset *token.FileSet, f *ast.File, line int) string {
	q := ""
	for _, d := range f.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || fd.Body == nil {
			continue
		}
		start := fset.Position(fd.Pos()).Line
		end := fset.Position(fd.End()).Line
		if line < start || line > end {
			continue
		}
		q = fd.Name.Name
		ast.Inspect(fd.Body, func(n ast.Node) bool {
			lit, ok := n.(*ast.FuncLit)
			if !ok {
				return true
			}
			if line >= fset.Position(lit.Pos()).Line && line <= fset.Position(lit.End()).Line {
				q = fd.Name.Name + " (closure)"
			}
			return true
		})
	}
	return q
}

func TestCheckStackSizeIsInlinedAtEveryCallSitePin(t *testing.T) {
	c := qt.New(t)

	cmd := exec.CommandContext(t.Context(), "go", "build", "-gcflags=-m=2", "-o", os.DevNull, ".")
	// A clean environment for the knobs that change inlining: an enclosing
	// `go test -race` or a GOFLAGS carrying -gcflags would change the result.
	cmd.Env = append(os.Environ(), "GOFLAGS=", "GOWORK=off")
	out, err := cmd.CombinedOutput()
	c.Assert(err, qt.IsNil, qt.Commentf("go build -gcflags=-m=2 failed:\n%s", out))

	fset := token.NewFileSet()
	parsed := map[string]*ast.File{}
	got := map[string]int{}
	var sites []string
	var cannot []string
	for ln := range strings.SplitSeq(string(out), "\n") {
		if strings.Contains(ln, "cannot inline (*MachineContext).checkStackSize") {
			cannot = append(cannot, ln)
		}
		m := inlineReport.FindStringSubmatch(ln)
		if len(m) == 0 || strings.Contains(m[1], "<autogenerated>") {
			continue
		}
		file := filepath.Base(m[1])
		f, ok := parsed[file]
		if !ok {
			var perr error
			f, perr = parser.ParseFile(fset, file, nil, 0)
			c.Assert(perr, qt.IsNil, qt.Commentf("parse %s named by %q", file, ln))
			parsed[file] = f
		}
		lineNo, aerr := strconv.Atoi(m[2])
		c.Assert(aerr, qt.IsNil)
		fn := enclosingFunc(fset, f, lineNo)
		sites = append(sites, file+":"+m[2]+" in "+fn)
		got[file+" "+fn]++
	}
	sort.Strings(sites)

	want := map[string]int{
		"machine_context.go Run":           7,
		"machine_context.go Run (closure)": 1,
	}
	c.Assert(got, qt.DeepEquals, want,
		qt.Commentf("checkStackSize must be inlined into exactly Run (x7) and the closure "+
			"inside Run (x1). A site missing here means it left the inline budget or a "+
			"caller stopped inlining it; an extra site means a call was added or moved "+
			"without updating this census.\nmatched sites:\n  %s\ncannot-inline reasons:\n  %s",
			strings.Join(sites, "\n  "), strings.Join(cannot, "\n  ")))
}
